def _pkt(run, dr, step):
    lo = step & 0xFF
    hi = (step >> 8) & 0xFF
    check = (0xAA + run + dr + lo + hi) & 0xFF
    return ' '.join(f'{b:02X}' for b in (0xAA, run, dr, lo, hi, check))


